CREATE TABLE concesionarios (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(100) NOT NULL,
    direccion VARCHAR(150) NOT NULL
);

CREATE TABLE coches (
    matricula        VARCHAR(7)     PRIMARY KEY,
    marca            VARCHAR(32)    NOT NULL,
    modelo           VARCHAR(32)    NOT NULL,
    precio_base      NUMERIC(12, 2) NOT NULL,
    concesionario_id BIGINT         NOT NULL REFERENCES concesionarios (id)
);

CREATE TABLE equipamientos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(40)    NOT NULL,
    precio_unit NUMERIC(12, 2) NOT NULL
);

CREATE TABLE coche_equipamiento (
    coche_matricula  VARCHAR(7) NOT NULL REFERENCES coches (matricula),
    equipamiento_id  BIGINT     NOT NULL REFERENCES equipamientos (id),
    PRIMARY KEY (coche_matricula, equipamiento_id)
);

CREATE TABLE mecanicos (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE propietarios (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni    VARCHAR(9)   NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE reparaciones (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha           DATE           NOT NULL,
    coste           NUMERIC(12, 2) NOT NULL,
    descripcion     VARCHAR(255)   NOT NULL,
    coche_matricula VARCHAR(7)     NOT NULL REFERENCES coches (matricula),
    mecanico_id     BIGINT         NOT NULL REFERENCES mecanicos (id)
);

-- UNIQUE en coche_matricula: la BD garantiza que un coche solo se vende una vez (1:1)
CREATE TABLE ventas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha            DATE           NOT NULL,
    precio_final     NUMERIC(12, 2) NOT NULL,
    coche_matricula  VARCHAR(7)     NOT NULL UNIQUE REFERENCES coches (matricula),
    propietario_id   BIGINT         NOT NULL REFERENCES propietarios (id),
    concesionario_id BIGINT         NOT NULL REFERENCES concesionarios (id)
);

CREATE INDEX idx_coches_concesionario ON coches (concesionario_id);
CREATE INDEX idx_reparaciones_coche ON reparaciones (coche_matricula);
CREATE INDEX idx_reparaciones_mecanico ON reparaciones (mecanico_id);
CREATE INDEX idx_ventas_concesionario ON ventas (concesionario_id);
